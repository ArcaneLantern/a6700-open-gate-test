"""The main-processor half of gen_a6700_write.py: the headers of readcheck.c's levels 19/20 (encoder side, MP4 header sites) and 29/30
(code words of av-cam.bin) for the A6700 2.00 designs (A6700 port, 2026-11-26). Run through gen_a6700_write.py.

Made from helper_fx30/gen_fx30_write.py (mp_header, ad_header: the A6700's av-cam.bin tables are the FX30's moved by 0xf90). What is new:
  - an encoder design may be large (the contributed 3840x2560 design has 475 av-cam.bin sites, the 5.76K one 487): MP_MAX is set;
  - a libmpr.so data site is a row of g_videoParamComb: its height alone (2 bytes at row + 6, guarded by the codec word and the width) or
    width and height (4 bytes at row + 4, guarded by the codec word);
  - a libmpr.so code site must be named in the design's libmpr_code_guards; the guards of all code sites may be listed under one of them;
  - a design may have no av-cam.bin site at all (pbmpr_a6700_v1: one libmpr.so instruction): its av-cam.bin table then holds only guards;
  - a playback design (levels 29/30) may have no data site, only data guards (pbaspect_a6700_v1, pbformat_a6700_v1).
Every stock byte is compared with the 2.00 files here.
"""
import hashlib
import json
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/a6700_200/0700_part_image/dev"
DES = ROOT / "modding/designs"
BUILD = "a6700_200"
# build_ogfile.OTHER_BUILDS["a6700_200"] (modding/A6700_PORT_ENCODER.md): the FX30's tables + 0xf90
DESC, DSIZE, NDESC, UNIT, CLIP, COMB, COMB_ROWS = 0x3936E8, 0x90, 689, 0x393648, 0x39156C, 0x27E590, 12
PROFILE_END = 0x3D6C78
AVCAM_PHYS = 0x401000000
MP_DESIGNS = ("ogfile2560_hs_s_a6700_v2", "ogfile2560_hs_s_a6700_v1", "ogfilesi2560_a6700_v1", "ogfile2560_full_a6700_v1", "ogfile57r260_a6700_v1", "pbmpr_a6700_v1")
AD_DESIGNS = ("avdec8k_a6700_v1", "pbaspect_a6700_v1", "pbformat_a6700_v1")
hx = lambda b: ", ".join("0x%02x" % x for x in b)
HEAD = "/* Generated by helper_a6700/gen_a6700_write.py from modding/designs/%s.json (A6700 2.00). Do not edit. */"


def design(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d.get("build") == BUILD, name
    return d


def files():
    return (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/libmpr.so").read_bytes()


def mp_tables(name):
    """The two tables of an encoder-side design, sites (kind 1) and guards (kind 0), sorted: {binary: [(off, kind, stock, new)]}."""
    d = design(name)
    av, lm = files()
    assert d["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    code_ok = {int(g["site"], 16): g["guards"] for g in d.get("libmpr_code_guards", [])}
    assert all(not p["code"] or (p["binary"] == "libmpr.so" and int(p["file_off"], 16) in code_ok) for p in d["patches"]), \
        "a code site must be in libmpr.so and named in libmpr_code_guards"
    assert sum(len(g) for g in code_ok.values()) > 0 or not code_ok, "code sites without any guard"
    tabs = {"av-cam.bin": [], "libmpr.so": []}
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        data = av if p["binary"] == "av-cam.bin" else lm
        assert 0 < len(old) == len(new) <= 16 and old != new and data[off:off + len(old)] == old
        tabs[p["binary"]].append((off, 1, old, new))
    overlaps = lambda a, n, sites: any(a < s + len(o) and s < a + n for s, _, o, _ in sites)
    # av-cam.bin guards, as gen_expected.py --mp: the 4K row of the unit-type table, clip-format row 5, each changed descriptor's profile key
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    assert not any(overlaps(a, len(b), tabs["av-cam.bin"]) for a, b in g_av), "a site lies in the unit-type table's 4K row or in clip-format row 5"
    for x in d["descriptors"]:
        assert 0 <= x["descriptor"] < NDESC
        o = DESC + x["descriptor"] * DSIZE + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        if not overlaps(o, 4, tabs["av-cam.bin"]):
            g_av.append((o, av[o:o + 4]))
    # libmpr.so guards: the file's first 16 bytes; per data site the row's bytes before it; per code site the instructions the design lists
    g_lm = [(0, lm[:16])]
    for off, _, old, new in tabs["libmpr.so"]:
        if off in code_ok:
            for g in code_ok[off]:
                a, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
                assert lm[a:a + len(b)] == b and 0 < len(b) <= 16
                g_lm.append((a, b))
            continue
        row, at = divmod(off - COMB, 0x18)
        assert 0 <= row < COMB_ROWS and (at, len(old)) in ((6, 2), (4, 4)), "a libmpr.so data site that is not a size of a g_videoParamComb row"
        assert struct.unpack_from("<2H", lm, COMB + row * 0x18 + 4) == (3840, 2160)
        g_lm.append((COMB + row * 0x18, lm[COMB + row * 0x18:off]))
    g_lm = sorted(set(g_lm))
    for binary, guards in (("av-cam.bin", g_av), ("libmpr.so", g_lm)):
        sites = tabs[binary]
        assert not any(overlaps(a, len(b), sites) for a, b in guards), "a guard overlaps a site"
        tabs[binary] = sorted(sites + [(a, 0, b, b"") for a, b in guards])
        assert all(tabs[binary][k][0] + len(tabs[binary][k][2]) <= tabs[binary][k + 1][0] for k in range(len(tabs[binary]) - 1)), "entries overlap"
    return d, tabs, lm


def mp_header(name):
    d, tabs, lm = mp_tables(name)
    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert (CLIP & ~0xFFF) <= first and first + span <= ((PROFILE_END + 0xFFF) & ~0xFFF), "an av-cam.bin site lies outside the pages of its tables"
    phoff, phentsize, phnum = struct.unpack_from("<Q", lm, 0x20)[0], *struct.unpack_from("<HH", lm, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lm, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lm, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0 and max(a + len(o) for a, _, o, _ in tabs["libmpr.so"]) <= load0[5], "a libmpr.so site lies outside the first segment"
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [HEAD % name,
           "/* av-cam.bin %s..., libmpr.so %s... (2.00). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */"
           % (d["artifact_sha256"]["av-cam.bin"][:16], d["artifact_sha256"]["libmpr.so"][:16]),
           '#define MP_DESIGN "%s"' % name,
           "#define MP_AV_FIRST 0x%xUL                 /* file offset of the first page read of av-cam.bin */" % first,
           "#define MP_AV_BYTES 0x%xUL                  /* whole pages: every entry of mp_av lies inside */" % span,
           "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };"]
    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    if longest > 96:
        out.insert(-1, "#define MP_MAX %d                          /* room for the entries of the longer table (levels 19 and 20) */" % ((longest + 31) & ~31))
    for binary, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, binary))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in tabs[binary]]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {b: (sum(1 for e in t if e[1] == 1), sum(1 for e in t if e[1] == 0)) for b, t in tabs.items()}, hex(first), hex(span)


AD_KVA, AD_ALIGN = 0xFFFFFFC001000000, 0x200000      # av-cam.bin's run address (file offset + this); the code page's alias rule (readcheck.c level 29)
AV_TABLES_LO = 0x391000                               # CLIP's page: av-cam.bin's encoder tables start here; the code the playback steps change lies below


def ad_header(name):
    """Levels 29/30: instruction words in ONE page of av-cam.bin's code (the whole page is carried and compared), and entries of one data page:
    sites and guards, or guards alone."""
    d = design(name)
    av, _ = files()
    assert d["kind"] == "avcam_code_data" and d["artifact_sha256"] == hashlib.sha256(av).hexdigest()
    assert int(d["kernel_va_base"], 16) == AD_KVA and int(d["avcam_phys"], 16) == AVCAM_PHYS
    code_page, data_page = int(d["code_page"], 16), int(d["data_page"], 16)
    assert code_page % 0x1000 == 0 and data_page % 0x1000 == 0 and code_page != data_page
    assert code_page + 0x1000 <= AV_TABLES_LO <= data_page, "the code page must lie in av-cam.bin's code, the data page above it"
    code = []
    for s in d["code_sites"]:
        off, old, new = int(s["file_off"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])
        assert off % 4 == 0 and len(old) == len(new) == 4 and old != new and off & ~0xFFF == code_page and av[off:off + 4] == old
        code.append((off, 1, old, new))
    data = []
    for s in d["data_sites"]:
        off, old, new = int(s["file_off"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])
        assert off % 4 == 0 and len(old) == len(new) == 4 and old != new and off & ~0xFFF == data_page and av[off:off + 4] == old
        data.append((off, 1, old, new))
    for g in d["data_guards"]:
        off, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
        assert 0 < len(b) <= 16 and off & ~0xFFF == (off + len(b) - 1) & ~0xFFF == data_page and av[off:off + len(b)] == b
        data.append((off, 0, b, b""))
    code.sort(), data.sort()
    for t in (code, data):
        assert all(t[k][0] + len(t[k][2]) <= t[k + 1][0] for k in range(len(t) - 1)), "entries overlap"
    assert 1 <= len(code) <= 16 and 1 <= len(data) <= 16
    page = av[code_page:code_page + 0x1000]
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [HEAD % name,
           "/* av-cam.bin %s...: %d code sites in page %#x (kernel text), %d data entries in page %#x. kind 1: a site; kind 0: a guard. */"
           % (d["artifact_sha256"][:16], len(code), code_page, len(data), data_page),
           '#define AD_DESIGN "%s"' % name,
           "#define AD_KVA 0x%xUL          /* av-cam.bin's run address: kernel address = file offset + this */" % AD_KVA,
           "#define AD_CODE_PAGE 0x%xUL" % code_page,
           "#define AD_DATA_PAGE 0x%xUL" % data_page,
           "#define AD_ALIGN 0x%xUL                 /* the code page is mapped at the kernel address's offset from a boundary of this size */" % AD_ALIGN,
           "struct ad_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };",
           "static const struct ad_site ad_code[] = {      /* file offsets; instruction words */"]
    out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in code]
    out += ["};", "static const struct ad_site ad_data[] = {      /* file offsets */"]
    out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in data]
    out += ["};", "static const u8 ad_code_file[4096] = {      /* the code page as in the file: every byte but the sites must hold this */"]
    out += ["    %s," % hx(page[k:k + 16]) for k in range(0, 0x1000, 16)]
    out += ["};"]
    (OUT / f"expected_ad_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(code), sum(1 for e in data if e[1]), sum(1 for e in data if not e[1]), hashlib.sha256(page).hexdigest()[:16]


def main():
    for n in MP_DESIGNS:
        print("mp header", n, mp_header(n))
    for n in AD_DESIGNS:
        print("ad header %s:" % n, ad_header(n))


if __name__ == "__main__":
    main()
