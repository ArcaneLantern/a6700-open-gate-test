"""Write the headers the A7 IV helper (helper/readcheck.c) needs to carry the A6700 2.00 designs (A6700 port, 2026-11-26).

  C:\\Python313\\python.exe -B gen_a6700_write.py

The A6700 kit is a contributed port conformed to this project's helper (modding/A6700_PORT.md). Its designs are in modding/designs in
our schemas (build/build_og_a6700.py, build/build_ogfile_a6700.py, build/build_avdec_a6700.py, build/build_lcd_a6700.py); this turns them
into the tables readcheck.c's write levels compile in. readcheck.c itself is used as it is. Made from helper_fx30/gen_fx30_write.py (the
same sensor family: several stored records, each in an NTSC and a PAL variant, so the sensor header sets MULTI_REC) and
helper_fx2/gen_fx2_write.py (the raw write buffer's header). This writes, into helper/:
  expected_dmm_dmmwb_a6700_v1.h              levels 13/14: the four memory-manager words, their unit records and the parents' records
  expected_sites_ogsq_a6700_v1.h             levels 5/6 (L5/L6): the table cells, the two picture records, five stored records (MULTI_REC)
  expected_sites_ogsq50_a6700_v1.h           levels 5/6 (Q5/Q6): the 50p mode 0x830 (PAL): cells, two picture records, one stored record
  expected_sites_ogsq32_a6700_v1.h           levels 5/6 (T5/T6): the exact 3:2 window, a test design in L5's place (MULTI_REC)
  expected_words_outsz2560_a6700_v1.h        levels 16/17 (L16/L17): the output-size word and its guards
  expected_words_og57cp_a6700_v1.h           levels 16/17 (K16/K17): the five words of the 5.76K state and their guards
  expected_words_lcdfill_a6700_v2.h          levels 16/17 (S16/S17): the rear screen at 3:2 and the frame rectangles
  expected_mp_ogfile2560_hs_s_a6700_v2.h     levels 19/20 (L19/L20): encoder side for 3840x2560 with the MP4 header sites
  expected_mp_ogfile2560_hs_s_a6700_v1.h     levels 19/20 (N19): the same without the MP4 header sites (--no-meta)
  expected_mp_ogfile57r260_a6700_v1.h        levels 19/20 (K19/K20): encoder side for 5760x3840
  expected_ad_avdec8k_a6700_v1.h             levels 29/30 (P29/P30): the playback decoder's channel
  expected_ad_pbaspect_a6700_v1.h            levels 29/30 (A29/A30): the playback aspect routine
  expected_ad_pbformat_a6700_v1.h            levels 29/30 (F29/F30): the playback format routine
Every stock byte is compared with the 2.00 files here.
"""
import hashlib
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/a6700_200/0700_part_image/dev"
DES = ROOT / "modding/designs"
sys.path.insert(0, str(ROOT / "build"))
import parse_dmmcfg  # noqa: E402

BUILD = "a6700_200"
BASE = 0x108000
IMAGE = (EX / "nflasha8/cpapp-b.bin").read_bytes()
IMAGE_END = BASE + len(IMAGE)
CP_DATA_LO = 0xD00000                                  # every cpapp-b.bin site of the sensor designs lies in its tables (picture records 0xd3885c on)
REC = 0x170
MODES = (0x820, 0x880, 0x890, 0x8C0, 0x8D0)            # the drive modes that share register-matrix column 1 and the picture-record pair
RATIO = {"ogsq_a6700_v1": (165, 191), "ogsq50_a6700_v1": (137, 162), "ogsq32_a6700_v1": (27, 32)}     # the vertical sampling ratio the stored records get at +6/+7
DMM_GROUPS = {0x8A: 0x6FA, 0x8E: 0x74D}                # the two layouts that offer the movie raw write buffer, and each one's parent key
LCD_REGIONS = HERE / "lcd_regions_a6700.json"          # written by build/build_lcd_a6700.py
hx = lambda b: ", ".join("0x%02x" % x for x in b)
HEAD = "/* Generated by helper_a6700/gen_a6700_write.py from modding/designs/%s.json (A6700 2.00). Do not edit. */"


def design(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d.get("build") == BUILD, name
    return d


def cp_rows(d, out):
    """The table/record sites of a sensor design as cp_site rows; appends their byte arrays to `out`."""
    assert d["artifact_sha256"] == hashlib.sha256(IMAGE).hexdigest() and d["record_size"] == REC
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and IMAGE[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and CP_DATA_LO <= lo and hi <= IMAGE_END, "span outside the image's tables"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    return sites, rows


CP_STRUCT = ["/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
             "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
             "static const struct cp_site cp_sites[] = {"]


def sites_header(name="ogsq_a6700_v1"):
    """Levels 5/6 with MULTI_REC: the sites, and the five stored records in two timing variants."""
    d = design(name)
    assert [int(m, 16) for m in d["modes"]] == list(MODES)
    out = [HEAD % name]
    sites, rows = cp_rows(d, out)
    out.insert(1, "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16]))
    assert sum(1 for _, o, _ in sites if len(o) == 3000) == 2 and len(sites) == d["summary_sites"] if "summary_sites" in d else True
    srs = d["stored_records"]
    offs = None
    stock, new = [], []
    for m in MODES:
        sr = srs[hex(m)]
        o = [int(x, 16) for x in sr["offsets_that_differ"]]
        assert offs is None or o == offs, "the modes' record sites differ"
        offs = o
        st_m, nw_m = [], []
        for v in ("ntsc", "pal"):
            s, n = bytes.fromhex(sr[v]["stock"]), bytes.fromhex(sr[v]["design"])
            assert len(s) == len(n) == REC and s[4:8] == b"\x01\x01\x01\x01" and n[6:8] == bytes(RATIO[name])
            assert struct.unpack_from("<I", s, 0x24)[0] == m, "the record is not this mode's"
            assert all(s[k] == n[k] for k in range(REC) if k not in o), "a changed byte outside the site list"
            st_m.append(bytes(s[k] for k in o))
            nw_m.append(bytes(n[k] for k in o))
        assert len({st_m[0], st_m[1], nw_m[0], nw_m[1]}) == 4, "a variant's bytes equal another's: the variant could not be told"
        stock.append(st_m)
        new.append(nw_m)
    assert offs[:2] == [6, 7] and 2 < len(offs) <= 128
    arr = lambda t: "{ " + ", ".join("{ " + ", ".join("{ %s }" % hx(v) for v in m) + " }" for m in t) + " }"
    out += ["#define MULTI_REC 1",
            "#define N_RECS %d" % len(MODES), "#define REC_VARIANTS 2",
            '#define REC_VARIANTS_TEXT "NTSC 60 Hz or PAL 50 Hz"',
            "#define REC_BYTES %d" % len(offs),
            "static const u32 rec_modes[N_RECS] = { %s };" % ", ".join("0x%x" % m for m in MODES),
            "static const char *const rec_mode_text[N_RECS] = { %s };" % ", ".join('"%#x"' % m for m in MODES),
            'static const char *const rec_variant_name[REC_VARIANTS] = { "NTSC (60 Hz)", "PAL (50 Hz)" };',
            "static const unsigned short rec_offs[REC_BYTES] = { %s };" % ", ".join("0x%x" % k for k in offs),
            "/* per mode (rec_modes order), per variant (NTSC, PAL): the bytes at rec_offs before and after */",
            "static const u8 rec_stock[N_RECS][REC_VARIANTS][REC_BYTES] = %s;" % arr(stock),
            "static const u8 rec_new[N_RECS][REC_VARIANTS][REC_BYTES] = %s;" % arr(new),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + len(MODES))] + CP_STRUCT + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs), [hex(m) for m in MODES]


def sites_header_one(name="ogsq50_a6700_v1"):
    """Levels 5/6 without MULTI_REC: the sites and ONE stored record, of the mode the header names (0x830), as a PAL camera computes it.
    An NTSC camera's record of that mode differs at site offsets, so pass 1 finds neither the stock nor the new bytes and nothing is written."""
    d = design(name)
    out = [HEAD % name]
    sites, rows = cp_rows(d, out)
    out.insert(1, "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16]))
    sr = d["stored_record"]
    assert sr["system"].lower().startswith("pal") and int(sr["mode"], 16) == int(d["mode_id"], 16) == 0x830
    r_stock, r_new = bytes.fromhex(sr["stock"]), bytes.fromhex(sr["design"])
    offs = [k for k in range(REC) if r_stock[k] != r_new[k]]
    assert len(r_stock) == len(r_new) == REC and r_stock[4:8] == b"\x01\x01\x01\x01" and r_new[6:8] == bytes(RATIO[name]) and offs[:2] == [6, 7] and 2 < len(offs) <= 128
    assert offs == [int(x, 16) for x in sr["offsets_that_differ"]] and struct.unpack_from("<I", r_stock, 0x24)[0] == 0x830
    ntsc = bytes.fromhex(d["stored_record_ntsc"]["stock"])            # what an NTSC camera holds there: it must not pass for either state
    assert bytes(ntsc[k] for k in offs) not in (bytes(r_stock[k] for k in offs), bytes(r_new[k] for k in offs)), "an NTSC camera's record would pass for the PAL one"
    out += ["static const unsigned short rec_offs[%d] = { %s };" % (len(offs), ", ".join("0x%x" % k for k in offs)),
            "static const u8 rec_stock[%d] = { %s };" % (len(offs), hx(bytes(r_stock[k] for k in offs))),
            "static const u8 rec_new[%d] = { %s };" % (len(offs), hx(bytes(r_new[k] for k in offs))),
            "#define REC_BYTES %d" % len(offs),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + 1),
            "#define MODE_ID %sU" % d["mode_id"], '#define MODE_TEXT "%s"' % d["mode_id"]] + CP_STRUCT + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs), d["mode_id"]


def dmm_header(name="dmmwb_a6700_v1"):
    """helper_fx2/gen_fx2_write.dmm_header for this body: four size words, three in group 0x8a (parent key 0x6fa, which must hold all three)
    and one in group 0x8e (parent key 0x74d, which holds it beside five other units). No layout is steered, so there is no spare key."""
    design_ = design(name)
    cfg = parse_dmmcfg.Config(parse_dmmcfg.find_file(BUILD), BUILD)
    assert hashlib.sha256(cfg.data).hexdigest() == design_["dmmcfg_sha256"]
    ram = lambda u: cfg.ram("unit_records", u["seq"] * 0x14)
    by_ram = {ram(u): u for g in cfg.groups for u in g["units"]}
    new_size = design_["summary"]["unit_size"]
    sites, recs, per_group = [], [], {}
    for s in design_["sites"]:
        a, old, new = int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])
        rec = next(r for r in by_ram if r <= a < r + 0x14)
        u, off = by_ram[rec], a - rec
        assert len(old) == len(new) == 4 and old != new and off == 12 and (a & 63) <= 60 and new == new_size.to_bytes(4, "little")
        assert u["key"] == 0x57F and u["group"]["gid"] in DMM_GROUPS and cfg.data[u["at"] + off:u["at"] + off + 4] == old
        per_group[u["group"]["gid"]] = per_group.get(u["group"]["gid"], 0) + 1
        sites.append((a, old, new))
        recs.append((rec, off, cfg.data[u["at"]:u["at"] + 0x14]))
    assert len(sites) == 4 and per_group == {0x8A: 3, 0x8E: 1} and new_size % 128 == 0 and len({r for r, _, _ in recs}) == 4
    # every key 0x57f record of the two layouts is a site: no unit of the old size is left in them
    assert sum(1 for g in cfg.groups if g["gid"] in DMM_GROUPS for u in g["units"] if u["key"] == 0x57F) == 4
    # each layout's whole need, with the new size, fits its parent's units (the write level checks only `fit` units of the new size)
    parents = []
    for gid, pkey in DMM_GROUPS.items():
        g = next(g for g in cfg.groups if g["gid"] == gid)
        need = sum(new_size if u["key"] == 0x57F else u["size"] for u in g["units"])
        assert all(pu["size"] >= need for pu in cfg.units_by_key[pkey]), "group %#x does not fit its parent with the new size" % gid
        parents += [(ram(pu), cfg.data[pu["at"]:pu["at"] + 0x14]) for pu in cfg.units_by_key[pkey]]
    fit = 3
    assert all(struct.unpack_from("<I", b, 12)[0] >= fit * new_size for _, b in parents)
    want = sorted(int(g["ram_address"], 16) for g in design_["parent_guards"])
    assert sorted(r for r, _ in parents) == want, "the design's parent records are not the file's records of keys 0x6fa and 0x74d"
    # busy keys: keys that only these two layouts make (group 0x8e also has a unit of key 0x2da, which other layouts make too: its object
    # says nothing about these layouts, and wherever group 0x8e is in force its 0x57f, 0x634 and 0x635 objects exist as well)
    in_groups = {u["key"] for g in cfg.groups if g["gid"] in DMM_GROUPS for u in g["units"]}
    elsewhere = {u["key"] for g in cfg.groups if g["gid"] not in DMM_GROUPS for u in g["units"]}
    busy = sorted(in_groups - elsewhere)
    assert busy == sorted(int(k, 16) for k in design_["dmm_ram"]["busy_keys"]) == [0x57F, 0x634, 0x635] and in_groups - set(busy) == {0x2DA}
    out = [HEAD % name,
           "/* The memory manager's RAM copy of its unit records (cpapp-b.bin 2.00, %#x on): %d words in %d records. */" % (cfg.ram("unit_records", 0), len(sites), len(recs)),
           '#define DMM_DESIGN "%s"' % name,
           "/* the new unit size, and how many units of it must fit each parent record */",
           "static const u32 dmm_fit[2] = { %dU, %dU };" % (new_size, fit),
           "struct dmm_site { u32 address; u8 stock[4]; u8 changed[4]; };",
           "static const struct dmm_site dmm_sites[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(old), hx(new)) for a, old, new in sites]
    out += ["};", "/* the record each site lies in, as in the file: every byte but the site's four (from site_off) must equal these */",
            "struct dmm_rec { u32 address; u32 site_off; u8 file[20]; };", "static const struct dmm_rec dmm_recs[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (r, off, hx(b)) for r, off, b in recs]
    out += ["};", "/* the records of the parent units (keys 0x6fa and 0x74d): all 20 bytes must equal the file's, and each must hold three units of the new size */",
            "static const struct dmm_rec dmm_parents[] = {"]
    out += ["    { 0x%x, 0xff, { %s } }," % (r, hx(b)) for r, b in parents]
    out += ["};", "/* a unit object of one of these keys in a division still in force: nothing is written */",
            "static const u32 dmm_busy_keys[] = { %s };" % ", ".join("0x%x" % k for k in busy)]
    (OUT / f"expected_dmm_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), [hex(r) for r, _ in parents], per_group


def regions(name, d):
    """Where a words design may have a site, and where only a guard."""
    if name.startswith("lcdfill"):
        r = json.loads(LCD_REGIONS.read_text(encoding="utf8"))[name]
        return tuple((int(a, 16), int(b, 16)) for a, b in r["sites"]), tuple((int(a, 16), int(b, 16)) for a, b in r["guards"])
    r = {k: (int(a, 16), int(b, 16)) for k, (a, b) in d["regions_a_site_or_guard_may_lie_in"].items()}
    assert r["size_table"] == (0x199EC7C, 0x199ECFC) and r["unit_count_setting"] == (0x199EEA8, 0x199EEB8)       # build/emu_size_table.py a6700_200
    if name == "outsz2560_a6700_v1":
        return (r["size_table"],), ()
    assert name == "og57cp_a6700_v1"
    return (r["size_table"], (0x199EEB0, 0x199EEB4), r["dmm_id_rows"]), (r["unit_count_setting"], r["dmm_key_lists"])


def words_header(name):
    d = design(name)
    assert d["kind"] == "ram_words"
    sites = [(int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])) for s in d["sites"]]
    guards = [(int(g["ram_address"], 16), bytes.fromhex(g["bytes"])) for g in d["guards"]]
    site_regions, guard_only = regions(name, d)
    within = lambda a, n, rs: any(lo <= a and a + n <= hi for lo, hi in rs)
    assert sites and all(len(o) == len(n) == 4 and o != n and a % 4 == 0 and within(a, 4, site_regions) for a, o, n in sites), name
    assert guards and all(0 < len(b) <= 16 and within(a, len(b), site_regions + guard_only) for a, b in guards), name
    for a, o, _ in sites:                                  # words inside the loaded image: the file's bytes
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + 4] == o
    for a, b in guards:
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + len(b)] == b
    assert not any(a < sa + 4 and sa < a + len(b) for a, b in guards for sa, _, _ in sites), "a guard overlaps a site"
    out = [HEAD % name, "/* Words of the coprocessor's tables (cpapp-b.bin 2.00): %d site(s), %d guard(s). */" % (len(sites), len(guards)),
           '#define WORDS_DESIGN "%s"' % name, "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };", "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in sites]
    out += ["};", "/* bytes beside the sites that must be as listed before anything is written */",
            "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in guards]
    out += ["};"]
    (OUT / f"expected_words_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(guards)


